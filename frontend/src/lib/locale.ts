/** Язык сайта в одном месте.
 *
 *  До второго языка дело может не дойти, но пока "ru" разбросано по файлам,
 *  любая попытка добавить английский начинается с поиска: где ещё забыли поменять.
 *  Одно место правды стоит одной строки и экономит день ошибок.
 */

const BASE_PATH = process.env.BASE_PATH ?? "/alyaev";

/** Код языка для атрибута lang в HTML. */
export const SITE_LANG = "ru";

/** Имя бренда: в заголовках, Open Graph и футере. */
export const SITE_NAME = "Дмитрий Аляев";

/** Локаль для Open Graph: язык_РЕГИОН, как требует протокол. */
export const SITE_OG_LOCALE = "ru_RU";

/** Префикс языковой версии в адресе.
 *
 *  Сейчас пустая строка: сайт одноязычный, адреса выглядят как /services/.
 *  При добавлении второго языка здесь появится "/en" — и сборка адресов
 *  (canonical, sitemap, OG) подхватит его сама, без правок в каждом файле.
 */
export const SITE_LANG_PREFIX = "";

/** basePath + языковой префикс: то, что нужно вычесть из адреса,
 *  чтобы получить путь страницы внутри языка. */
export function langBasePath(): string {
  return BASE_PATH + SITE_LANG_PREFIX;
}
