SETTINGS = [
    {"key": "contacts", "value": {"telegram": "@alyaev", "email": "", "phone": "", "note": "Заполняется владельцем"}},
    {"key": "brand", "value": {"name": "Дмитрий Аляев", "tagline": "AI & Business Automation"}},
    {"key": "analytics", "value": {"metrika_id": "", "ga4_id": ""}},
    {"key": "privacy", "value": {"policy_version": "1.0", "policy_date": "2026-11-24"}},
]


def run() -> None:
    """Записывает категории, услуги, настройки и SEO-записи."""
    with SessionLocal() as session:
        cat_ids = {}
        for item in CATEGORIES:
            row = session.scalars(
                select(ServiceCategory).where(ServiceCategory.slug == item['slug'])
            ).first()
            if row is None:
                row = ServiceCategory(**item)
                session.add(row)
            else:
                for key, value in item.items():
                    setattr(row, key, value)
            session.flush()
            cat_ids[item['slug']] = row.id
        for item in SERVICES:
            cat_slug = item.pop('category_slug')
            row = session.scalars(select(Service).where(Service.slug == item['slug'])).first()
            if row is None:
                row = Service(status='published', category_id=cat_ids[cat_slug])
                session.add(row)
            for key, value in item.items():
                setattr(row, key, value)
            row.category_id = cat_ids[cat_slug]
            row.status = 'published'
        for setting in SETTINGS:
            row = session.scalars(select(SiteSetting).where(SiteSetting.key == setting['key'])).first()
            if row is None:
                session.add(SiteSetting(**setting))
            else:
                row.value = setting['value']
        if session.scalars(select(SeoMetadata).where(SeoMetadata.path == '/')).first() is None:
            session.add(SeoMetadata(
                entity_type='page', path='/',
                title='Автоматизация бизнеса и AI-разработка — Дмитрий Аляев',
                description='Разрабатываю и внедряю решения для автоматизации бизнеса: Telegram-боты, AI-ассистенты, интеграции и сайты под конкретные процессы.',
                h1='Автоматизация бизнеса и AI-разработка',
            ))
        session.commit()


if __name__ == "__main__":
    run()
